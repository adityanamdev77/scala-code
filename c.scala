object Main {
  def main(args: Array[String]): Unit = {

    val a: Int = 10
    val b: Long = 100000L
    val c: Double = 10.5
    val d: Float = 5.5f
    val e: Char = 'A'
    val f: String = "Scala"
    val g: Boolean = true

    println("Int: " + a)
    println("Long: " + b)
    println("Double: " + c)
    println("Float: " + d)
    println("Char: " + e)
    println("String: " + f)
    println("Boolean: " + g)
  }
}